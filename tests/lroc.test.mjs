test('native LROC values and separate quality propagate through complete dependency windows',()=>{
 const ds=DATASETS.find(d=>d.id==='lroc-nassau02'),sample=JSON.parse(readFileSync(new URL('../fixtures/lroc/nassau02/sample.json',import.meta.url)));
 assert.deepEqual(ds.heights,sample.heights);assert.deepEqual(ds.quality.codes,sample.quality_codes);
 assert.ok(ds.origins.every(o=>o==='undocumented'));
 const ev=evaluate(ds),q=query(ev,'combined',{row:11,col:18});
 assert.equal(q.branches.slope.quality.suspicious,0);assert.equal(q.branches.roughness.quality.suspicious,8);
 assert.equal(q.quality.total,q.sourceCells.length);assert.equal(q.quality.suspicious,q.sourceCells.filter(c=>c.quality.code===3).length);
 assert.ok(Math.abs(q.branches.slope.value-3.815859004321798)<1e-10);
 assert.ok(Math.abs(q.branches.roughness.value-.34074126266534155)<1e-10);
 assert.equal(q.origin.text,'Cell origin not supplied');
 assert.equal(q.production.method,'LROC stereo reconstruction');
 assert.equal(q.production.scope,'delivery');
 assert.equal(q.production.cellHistory,'Individual filling history unavailable');
 assert.equal(q.origin.counts.interpolated,0);
 const changed=evaluate({...ds,quality:{...ds.quality,codes:ds.quality.codes.map(()=>14)}});
 assert.deepEqual(changed.records.slope.map(r=>r.value),ev.records.slope.map(r=>r.value));
 assert.equal(query(changed,'combined',{row:11,col:18}).quality.suspicious,0);
});
