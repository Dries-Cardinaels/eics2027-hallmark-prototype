test('slope uses only eight neighbours: centre status and missing value cannot contaminate it',()=>{
 const base={id:'test',W:5,H:5,res:2,heights:Array(25).fill(0),origins:Array(25).fill('observed'),quality:{kind:'stereo',codes:Array(25).fill(14)}};
 base.heights[12]=10;base.quality.codes[12]=3;
 const e=evaluate(base);
 assert.equal(e.records.slope[0].value,0);
 // Quality summaries are computed at query time from the declarations; records store none.
 assert.equal(e.records.slope[0].quality,undefined);
 assert.equal(qualityAt(e,'slope',0).total,8);
 assert.equal(qualityAt(e,'slope',0).suspicious,0);
 assert.equal(qualityAt(e,'roughness',0).suspicious,1);
 assert.equal(qualityAt(e,'combined',0).suspicious,1);
 assert.deepEqual(query(e,'combined',0).quality,qualityAt(e,'combined',0));
 assert.equal(query(e,'slope',0).sourceCells.length,8);
 assert.ok(!query(e,'slope',0).sourceCells.some(c=>c.index===12));
 const missing={...base,heights:[...base.heights],origins:[...base.origins]};
 missing.heights[12]=NaN;missing.origins[12]='absent';
 assert.equal(evaluate(missing).records.slope[0].available,true);
 assert.equal(evaluate(missing).records.roughness[0].available,false);
 base.quality.codes[13]=3;base.heights[13]=1;
 const changed=evaluate(base);
 assert.equal(qualityAt(changed,'slope',0).suspicious,1);
 assert.ok(changed.records.slope[0].value>0);
});

